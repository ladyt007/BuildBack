-- ---------------------------------------------------------------------------
-- Follows
-- ---------------------------------------------------------------------------
create table public.follows (
  user_id uuid not null references public.profiles (id) on delete cascade,
  business_id uuid not null references public.businesses (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, business_id)
);

alter table public.follows enable row level security;

create policy "Members see their follows" on public.follows for select using (user_id = auth.uid());
create policy "Members follow" on public.follows for insert with check (user_id = auth.uid());
create policy "Members unfollow" on public.follows for delete using (user_id = auth.uid());

create function public.sync_follower_count() returns trigger
  language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    update public.businesses set follower_count = follower_count + 1 where id = new.business_id;
  else
    update public.businesses set follower_count = greatest(follower_count - 1, 0) where id = old.business_id;
  end if;
  return null;
end;
$$;

create trigger follows_count after insert or delete on public.follows
  for each row execute function public.sync_follower_count();

-- ---------------------------------------------------------------------------
-- Supports: self-reported gifts. BuildBack never handles the money.
-- ---------------------------------------------------------------------------
create table public.supports (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  target_type text not null check (target_type in ('business', 'neighbor')),
  target_id uuid not null,
  amount numeric(10, 2) check (amount is null or amount >= 0),
  created_at timestamptz not null default now()
);

create index supports_target_idx on public.supports (target_type, target_id);

alter table public.supports enable row level security;

create policy "Members see their own gifts" on public.supports for select using (user_id = auth.uid());
create policy "Members record gifts" on public.supports for insert with check (user_id = auth.uid());

create function public.sync_supporter_count() returns trigger
  language plpgsql security definer set search_path = public as $$
begin
  -- Count each person once per business or neighbor.
  if exists (
    select 1 from public.supports
     where user_id = new.user_id and target_id = new.target_id and id <> new.id
  ) then
    return null;
  end if;
  if new.target_type = 'business' then
    update public.businesses set supporter_count = supporter_count + 1 where id = new.target_id;
  else
    update public.neighbor_requests set supporter_count = supporter_count + 1 where id = new.target_id;
  end if;
  return null;
end;
$$;

create trigger supports_count after insert on public.supports
  for each row execute function public.sync_supporter_count();

-- ---------------------------------------------------------------------------
-- Community sponsors (sold directly; no ad networks)
-- ---------------------------------------------------------------------------
create table public.sponsors (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  tagline text not null,
  url text not null,
  city text,
  state text,
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.sponsors enable row level security;

create policy "Anyone can see active sponsors"
  on public.sponsors for select using (starts_at <= now() and (ends_at is null or ends_at > now()));

-- ---------------------------------------------------------------------------
-- Community-wide impact numbers
-- ---------------------------------------------------------------------------
create function public.community_stats() returns json
  language sql stable security definer set search_path = public as $$
  select json_build_object(
    'businessesHelped', (select count(*) from public.businesses where supporter_count > 0),
    'neighborsHelped', (select count(*) from public.neighbor_requests where supporter_count > 0),
    'members', (select count(*) from public.profiles),
    'wishes', (select count(*) from public.wishes),
    'businessesListed', (select count(*) from public.businesses where not is_hidden)
  );
$$;

grant execute on function public.community_stats() to anon, authenticated;
grant execute on function public.review_neighbor_request(uuid, boolean) to authenticated;
