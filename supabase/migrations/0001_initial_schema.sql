-- ---------------------------------------------------------------------------
-- Profiles (one per account)
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  email text not null default '',
  member_number bigint generated by default as identity,
  joined_at timestamptz not null default now(),
  is_admin boolean not null default false,
  home_lat double precision,
  home_lng double precision,
  home_label text
);

alter table public.profiles enable row level security;

create policy "Members can read their own profile"
  on public.profiles for select using (id = auth.uid());

create policy "Members can update their own profile"
  on public.profiles for update using (id = auth.uid());

-- Members may only change these columns; is_admin and member_number stay locked.
revoke update on public.profiles from authenticated;
grant update (display_name, home_lat, home_lng, home_label) on public.profiles to authenticated;

create function public.is_admin() returns boolean
  language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

-- Create a profile automatically when someone signs up.
create function public.handle_new_user() returns trigger
  language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', ''), coalesce(new.email, ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Businesses
-- ---------------------------------------------------------------------------
create table public.businesses (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references public.profiles (id) on delete set null,
  name text not null,
  category text not null,
  kind text not null default '',
  ownership_tags text[] not null default '{}',
  description text not null default '',
  city text not null default '',
  state text not null default '',
  lat double precision not null,
  lng double precision not null,
  image_url text,
  support_url text,
  website text,
  phone text,
  status text not null default 'open'
    check (status in ('open', 'reopening', 'struggling', 'temporarily_closed')),
  is_pro boolean not null default false,
  featured_until timestamptz,
  is_hidden boolean not null default false,
  follower_count integer not null default 0,
  supporter_count integer not null default 0,
  created_at timestamptz not null default now()
);

create index businesses_location_idx on public.businesses (lat, lng);

alter table public.businesses enable row level security;

create policy "Anyone can see listed businesses"
  on public.businesses for select using (not is_hidden or owner_id = auth.uid() or public.is_admin());

create policy "Members can list their own business"
  on public.businesses for insert with check (owner_id = auth.uid());

create policy "Owners can edit their business"
  on public.businesses for update using (owner_id = auth.uid());

-- Paid features (is_pro, featured_until) and counters are set by BuildBack, never by owners.
revoke insert, update on public.businesses from authenticated;
grant insert (owner_id, name, category, kind, ownership_tags, description, city, state, lat, lng,
              image_url, support_url, website, phone, status)
  on public.businesses to authenticated;
grant update (name, category, kind, ownership_tags, description, city, state, lat, lng,
              image_url, support_url, website, phone, status)
  on public.businesses to authenticated;

-- ---------------------------------------------------------------------------
-- Business status updates
-- ---------------------------------------------------------------------------
create table public.status_updates (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index status_updates_business_idx on public.status_updates (business_id, created_at desc);

alter table public.status_updates enable row level security;

create policy "Anyone can read status updates"
  on public.status_updates for select using (true);

create policy "Owners can post updates"
  on public.status_updates for insert with check (
    exists (select 1 from public.businesses b where b.id = business_id and b.owner_id = auth.uid())
  );

-- ---------------------------------------------------------------------------
-- Neighbors in need (reviewed before they're public)
-- ---------------------------------------------------------------------------
create table public.neighbor_requests (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  first_name text not null,
  title text not null,
  story text not null,
  need text not null,
  goal_amount numeric(10, 2),
  fundraiser_url text not null,
  city text not null default '',
  state text not null default '',
  lat double precision not null,
  lng double precision not null,
  image_url text,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'fulfilled')),
  supporter_count integer not null default 0,
  reviewed_by uuid references public.profiles (id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index neighbor_requests_location_idx on public.neighbor_requests (status, lat, lng);

alter table public.neighbor_requests enable row level security;

create policy "Approved requests are public; owners and reviewers see the rest"
  on public.neighbor_requests for select
  using (status in ('approved', 'fulfilled') or owner_id = auth.uid() or public.is_admin());

create policy "Members can ask for help"
  on public.neighbor_requests for insert with check (owner_id = auth.uid());

revoke insert, update on public.neighbor_requests from authenticated;
grant insert (owner_id, first_name, title, story, need, goal_amount, fundraiser_url, city, state, lat, lng, image_url)
  on public.neighbor_requests to authenticated;

create function public.review_neighbor_request(request_id uuid, approve boolean) returns void
  language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then
    raise exception 'Only reviewers can approve requests';
  end if;
  update public.neighbor_requests
     set status = case when approve then 'approved' else 'rejected' end,
         reviewed_by = auth.uid(),
         reviewed_at = now()
   where id = request_id;
end;
$$;

