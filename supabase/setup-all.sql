create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  email text not null default '',
  member_number bigint generated by default as identity,
  joined_at timestamptz not null default now(),
  is_admin boolean not null default false,
  home_lat double precision,
  home_lng double precision,
  home_label text
);

alter table public.profiles enable row level security;

create policy "Members can read their own profile"
  on public.profiles for select using (id = auth.uid());

create policy "Members can update their own profile"
  on public.profiles for update using (id = auth.uid());

-- Members may only change these columns; is_admin and member_number stay locked.
revoke update on public.profiles from authenticated;
grant update (display_name, home_lat, home_lng, home_label) on public.profiles to authenticated;

create function public.is_admin() returns boolean
  language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

-- Create a profile automatically when someone signs up.
create function public.handle_new_user() returns trigger
  language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', ''), coalesce(new.email, ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

